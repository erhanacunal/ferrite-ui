#!/usr/bin/env python3
"""ferrite_build.py — JSON proje dosyasından flash filesystem binary'si oluşturur.

Flash FS layout (W25Q256):
  0x000000 - 0x000FFF : Reserved (4KB)
  0x001000 - 0x00100F : Header (16B: magic + version + screen + count + checksum)
  0x001010 - 0x001FFF : Resource Table (max 127 × 32B)
  0x002000+            : Resource data (packed)

Usage:
  python ferrite_build.py project.json -o flash.bin
  python ferrite_build.py project.json --info
  python ferrite_build.py project.json --expand   # print fully expanded source
                                                   # (includes + dispatchers) and exit
  python ferrite_build.py project.json --disasm   # build in memory and print every
                                                   # resource; programs disassembled
                                                   # (add -o to also write the image)
  python ferrite_build.py flash.bin --disasm      # same for an already built image

JSON format:
  {
    "version": 1,
    "screen": [800, 480],
    "fonts": [
      {"name": "sans12", "font_id": 1, "header": "assets/sans12.bin", "data": "assets/sans12_bmp.bin"}
    ],
    "images": [
      {"name": "logo", "image_id": 1, "source": "assets/logo.png", "mode": "auto", "max_colors": 256}
    ],
    "programs": [
      {"name": "main", "source": "main.fl", "exec_mode": "ram|flash", "widget_page": false}
    ],
    "files": [
      {"name": "config", "source": "data/config.bin"}
    ],
    "memory": {
      "strpool_bytes": 4096, "max_strings": 96, "uart_rx_bytes": 512,
      "max_widgets": 200, "max_ext": 150,
      "eval_stack": 32, "call_stack": 12, "cb_queue": 16, "anim_slots": 8
    }
  }

  "widget_page": true moves static widget setup out of the program into a
  RES_PAGE resource with the program's name (see docs/bytecode.md). Set it
  at the top level for every program, or on a program to override that.

  "memory" is optional; it becomes the RES_SYSCFG entry "sys" that sizes the
  runtime pools at boot (see ferrite-core/src/syscfg.rs). Omitted keys keep
  the firmware default. All pools come out of the heap, so an oversized
  request fails at boot with error 7 (insufficient memory).
"""

import json
import struct
import sys
from pathlib import Path

# ferrite_cc ve ferrite_img'den import
sys.path.insert(0, str(Path(__file__).parent))
import ferrite_devices

# --- Constants (fs.rs ile birebir aynı) ---

MAGIC = b"FERR"
FS_BASE = 0x1000       # Sector 0 reserved for ConfigStore
HEADER_OFFSET = 0x0000  # Relative to FS image start (written at FS_BASE in flash)
HEADER_SIZE = 16
TABLE_OFFSET = HEADER_OFFSET + HEADER_SIZE  # 0x10
ENTRY_SIZE = 32
MAX_RESOURCES = 1000

RES_FONT = 0
RES_IMAGE = 1
RES_PROGRAM = 2
RES_PAGE = 3
RES_FILE = 4
RES_SYSCFG = 5

# Resource flags (stored in entry reserved[0], byte 28)
RES_FLAG_FLASH_EXEC = 0x01

KIND_NAMES = {RES_FONT: "FONT", RES_IMAGE: "IMAGE", RES_PROGRAM: "PROGRAM", RES_PAGE: "PAGE",
              RES_FILE: "FILE", RES_SYSCFG: "SYSCFG"}

# --- Image conversion (shared encoder in ferrite_img.py) ---

def convert_image(source_path: str, mode: str = "auto", max_colors: int = 256,
                  want_alpha: bool = False) -> bytes:
    """PNG → FI binary via the shared ferrite_img encoder.

    `want_alpha` comes from the target device's caps.image_alpha; alpha is
    only emitted when the source actually has non-opaque pixels.
    """
    # Deferred import keeps the PIL dependency lazy (as before); ferrite_img
    # itself reports a clear error and exits when Pillow is missing.
    import ferrite_img

    img = ferrite_img.Image.open(source_path)
    fi_data, _stats = ferrite_img.convert_bytes(
        img, mode=mode, max_colors=max_colors, want_alpha=want_alpha)
    return fi_data


# --- Debug symbols ---

def _write_debug_sidecar(source_path: str, image: bytes) -> str | None:
    """Write .dbg debug-symbol sidecar alongside the source file.

    Debug symbols are already generated by ferrite_lang and carried on the
    _ImageBytes object.  This helper extracts them and persists them to disk
    so they are available for disassembly and stack-traces.
    """
    symbols = getattr(image, 'debug_symbols', None)
    if not symbols:
        return None
    dbg_path = str(Path(source_path).with_suffix('.dbg'))
    with open(dbg_path, 'w', encoding='utf-8') as f:
        json.dump(symbols, f, indent=2, sort_keys=True)
        f.write('\n')
    return dbg_path


# --- Program compilation ---

def compile_program(source_path: str, include_dirs=None, render_mode="dirty",
                    widget_page=False) -> bytes:
    """Ferrite lang source → VM image (header + opcodes). With widget_page,
    static widget setup moves to the image's `.page` (RES_PAGE contents)."""
    try:
        from ferrite_lang import build_image, CompileError
    except ImportError:
        print(f"Warning: ferrite_lang not available, reading {source_path} as raw binary",
              file=sys.stderr)
        return Path(source_path).read_bytes()

    source = Path(source_path).read_text(encoding="utf-8")
    try:
        image = build_image(source, filename=source_path, include_dirs=include_dirs,
                            render_mode=render_mode, widget_page=widget_page)
        _write_debug_sidecar(source_path, image)
        return image
    except CompileError as e:
        raise CompileError(f"{source_path}: {e}") from e


# --- Flash filesystem builder ---

# RES_SYSCFG record — keep in sync with ferrite-core/src/syscfg.rs.
SYSCFG_NAME = "sys"
SYSCFG_MAGIC = 0x4353  # "SC" LE
SYSCFG_VERSION = 1
# key -> (struct offset, struct format, max value)
SYSCFG_FIELDS = {
    "strpool_bytes": (4, "<I", 0xFFFFFFFF),
    "max_strings": (8, "<H", 0xFFFE),
    "uart_rx_bytes": (10, "<H", 32 * 1024),
    "max_widgets": (12, "<H", 1024),
    "max_ext": (14, "<H", 1024),
    "eval_stack": (16, "<B", 255),
    "call_stack": (17, "<B", 255),
    "cb_queue": (18, "<B", 255),
    "anim_slots": (19, "<B", 255),
}


def build_syscfg(memory: dict) -> bytes:
    """project.json "memory" block -> 32-byte RES_SYSCFG record."""
    unknown = set(memory) - set(SYSCFG_FIELDS)
    if unknown:
        raise ValueError(f"memory: unknown key(s) {', '.join(sorted(unknown))} "
                         f"(valid: {', '.join(SYSCFG_FIELDS)})")
    rec = bytearray(32)
    struct.pack_into("<HB", rec, 0, SYSCFG_MAGIC, SYSCFG_VERSION)
    for key, value in memory.items():
        offset, fmt, max_value = SYSCFG_FIELDS[key]
        if not isinstance(value, int) or isinstance(value, bool) or not 0 <= value <= max_value:
            raise ValueError(f"memory.{key}: expected an integer 0..{max_value}, got {value!r}")
        if key == "uart_rx_bytes" and value & (value - 1):
            rounded = 1 << value.bit_length()
            print(f"warning: memory.uart_rx_bytes {value} is not a power of two — "
                  f"firmware rounds it up to {rounded}", file=sys.stderr)
        struct.pack_into(fmt, rec, offset, value)
    return bytes(rec)


def build_fs(project: dict, resources: list[tuple[str, int, bytes, int]],
             fs_base: int = FS_BASE) -> bytes:
    """Flash filesystem binary oluştur.

    resources: [(name, kind, data, flags), ...]
    `fs_base` is the absolute flash address the image is written to (the
    board's Platform::FS_BASE). Resource offsets in the TOC are absolute, so
    this MUST match where the device mounts the FS or lookups read garbage.
    """
    if len(resources) > MAX_RESOURCES:
        raise ValueError(f"Too many resources: {len(resources)} (max {MAX_RESOURCES})")

    screen = project.get("screen", [800, 480])
    version = project.get("version", 2)
    count = len(resources)

    # Data starts right after the resource table (relative to image start)
    data_base_rel = TABLE_OFFSET + count * ENTRY_SIZE

    # Resource table and data blob
    table = bytearray()
    data_blob = bytearray()

    for name, kind, data, flags in resources:
        # Name: 16 byte null-padded ASCII
        name_bytes = name.encode("ascii")[:15]
        name_padded = name_bytes + b'\x00' * (16 - len(name_bytes))

        # Offset: absolute flash address (FS image is written at fs_base)
        offset = fs_base + data_base_rel + len(data_blob)

        # Entry: name[16] + kind(1) + pad(3) + offset(4) + size(4) + reserved(4)
        entry = bytearray(ENTRY_SIZE)
        entry[0:16] = name_padded
        entry[16] = kind
        # [17:20] = padding (zeros)
        struct.pack_into("<I", entry, 20, offset)
        struct.pack_into("<I", entry, 24, len(data))
        entry[28] = flags  # resource flags (e.g. RES_FLAG_FLASH_EXEC)

        table.extend(entry)
        data_blob.extend(data)

    # Checksum: additive sum of table bytes
    checksum = sum(table) & 0xFFFFFFFF

    # Header (16 bytes)
    header = bytearray(HEADER_SIZE)
    header[0:4] = MAGIC
    struct.pack_into("<H", header, 4, version)
    struct.pack_into("<H", header, 6, screen[0])
    struct.pack_into("<H", header, 8, screen[1])
    struct.pack_into("<H", header, 10, count)
    struct.pack_into("<I", header, 12, checksum)

    # Full binary — header + table + data, no gaps
    binary = bytearray()
    binary.extend(header)
    binary.extend(table)
    binary.extend(data_blob)

    return bytes(binary)


# --- Source expansion (debug aid) ---

def dump_expanded(project_path: str):
    """Print the fully expanded source for each program/page in the project —
    `#include`s inlined and the generated widget-callback dispatchers
    (`__on_click_dispatch`, …) appended — i.e. exactly what the compiler
    tokenizes. Mirrors `build_image`'s preprocessing so include paths and
    `set(on_click, @h)` / dot-syntax wiring resolve identically to a real build.
    """
    from ferrite_lang import preprocess, _generate_dispatchers
    # Source files are UTF-8 (arrows like → in comments, accented text). Force
    # UTF-8 on stdout so redirecting to a file on a non-UTF-8 console (e.g.
    # Windows cp1254) doesn't raise UnicodeEncodeError.
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except (AttributeError, ValueError):
        pass
    project_dir = Path(project_path).parent
    project = json.loads(Path(project_path).read_text(encoding="utf-8"))
    include_dirs = [str(project_dir / d) for d in project.get("include_dirs", [])]

    sources = [p["source"] for p in project.get("pages", [])
               if isinstance(p, dict) and "source" in p]
    sources += [p["source"] for p in project.get("programs", [])]

    for rel in sources:
        path = project_dir / rel
        expanded = preprocess(path.read_text(encoding="utf-8"), str(path), include_dirs)
        dispatchers = _generate_dispatchers(expanded)
        if dispatchers:
            expanded = expanded + "\n\n" + dispatchers
        print(f"// ===== expanded source: {rel} =====")
        print(expanded)
        print()


# --- Main build pipeline ---

def build(project_path: str, output_path: str | None) -> dict:
    """JSON proje → flash binary. output_path None = don't write the file
    (the binary is returned in the stats as "binary")."""
    project_dir = Path(project_path).parent
    project = json.loads(Path(project_path).read_text(encoding="utf-8"))

    # Validate against the device definition when the project declares one.
    # Projects without a "device" key build exactly as before (legacy).
    device_id = project.get("device")
    device = None
    fs_base = FS_BASE
    if device_id is not None:
        if device_id not in ferrite_devices.load_devices():
            print(f"warning: unknown device '{device_id}' — skipping device checks",
                  file=sys.stderr)
        else:
            device = ferrite_devices.device_spec(device_id)
            fs_base = device.get("fs_base", FS_BASE)
            screen = project.get("screen")
            if screen is not None and tuple(screen) != device["screen"]:
                dw, dh = device["screen"]
                print(f"warning: project screen {screen[0]}x{screen[1]} does not "
                      f"match device '{device_id}' ({dw}x{dh})", file=sys.stderr)
            render_mode = project.get("render_mode", device["render_mode"])
            if render_mode not in device["render_modes"]:
                raise ValueError(
                    f"render_mode '{render_mode}' is not supported by device "
                    f"'{device_id}' (supported: {', '.join(device['render_modes'])})")

    # Resolve include directories relative to project dir
    include_dirs = [str(project_dir / d) for d in project.get("include_dirs", [])]

    resources = []  # (name, kind, data)

    # 1. Fonts — sparse binary resource (num_glyphs + y_advance + font_id + codepoints + glyphs + bitmap)
    font_ids_seen = set()
    for font in project.get("fonts", []):
        name = font["name"]
        font_id = font.get("font_id")
        if font_id is None:
            print(f"Error: font '{name}' missing required 'font_id' field", file=sys.stderr)
            sys.exit(1)
        if font_id == 0:
            print(f"Error: font '{name}' has font_id=0 (reserved for embedded font)", file=sys.stderr)
            sys.exit(1)
        if font_id < 0 or font_id > 254:
            print(f"Error: font '{name}' font_id must be 1-254, got {font_id}", file=sys.stderr)
            sys.exit(1)
        if font_id in font_ids_seen:
            print(f"Error: duplicate font_id={font_id} for font '{name}'", file=sys.stderr)
            sys.exit(1)
        font_ids_seen.add(font_id)

        if "header" in font or "data" in font:
            print(f"Error: font '{name}' uses old 'header'/'data' keys — re-import with ferrite_font_converter.py",
                  file=sys.stderr)
            sys.exit(1)

        font_path = project_dir / font["file"]
        font_data = bytearray(font_path.read_bytes())

        # Patch the project-assigned font_id into the header. The byte offset
        # differs by format: V1 (legacy 1bpp) keeps font_id at byte 3, while
        # V2 (2bpp, magic 0x00 0x02) keeps it at byte 5 — byte 3 there is the
        # high byte of num_glyphs, so writing to it corrupts the glyph count.
        if len(font_data) < 4:
            print(f"Error: font '{name}' binary too small ({len(font_data)} bytes)", file=sys.stderr)
            sys.exit(1)
        if font_data[0] == 0x00 and font_data[1] == 0x02:
            # V2: [0..1]=magic, [2..3]=num_glyphs, [4]=y_adv, [5]=font_id, [6]=bpp
            if len(font_data) < 7:
                print(f"Error: font '{name}' V2 binary too small ({len(font_data)} bytes)",
                      file=sys.stderr)
                sys.exit(1)
            font_data[5] = font_id
        else:
            # V1: [0..1]=num_glyphs, [2]=y_adv, [3]=font_id
            font_data[3] = font_id

        resources.append((name, RES_FONT, bytes(font_data), 0))

    # 2. Images — PNG → FI format (header extended to 9 bytes with image_id)
    image_ids_seen = set()
    for image in project.get("images", []):
        name = image["name"]
        image_id = image.get("image_id")
        if image_id is None:
            print(f"Error: image '{name}' missing required 'image_id' field", file=sys.stderr)
            sys.exit(1)
        if image_id == 0:
            print(f"Error: image '{name}' has image_id=0 (reserved for 'no image')", file=sys.stderr)
            sys.exit(1)
        if image_id < 0 or image_id > 254:
            print(f"Error: image '{name}' image_id must be 1-254, got {image_id}", file=sys.stderr)
            sys.exit(1)
        if image_id in image_ids_seen:
            print(f"Error: duplicate image_id={image_id} for image '{name}'", file=sys.stderr)
            sys.exit(1)
        image_ids_seen.add(image_id)

        source = project_dir / image["source"]
        mode = image.get("mode", "auto")
        max_colors = image.get("max_colors", 256)
        # Alpha encoding only for devices that can blend (caps.image_alpha);
        # legacy projects (no device key) never emit it.
        want_alpha = bool(device and device["caps"].get("image_alpha"))

        fi_data = bytearray(convert_image(str(source), mode=mode, max_colors=max_colors,
                                          want_alpha=want_alpha))
        if want_alpha and len(fi_data) >= 7 and fi_data[6] & 0x04:
            print(f"  note: image '{name}' encoded with alpha (FI flags bit 2)")
        # FI header is 8 bytes; extend to 9 by inserting image_id at byte 8
        # Original: magic[2] + width[2] + height[2] + flags[1] + colors[1] = 8 bytes
        # New:      ... + image_id[1] = 9 bytes
        if len(fi_data) >= 8:
            fi_data.insert(8, image_id)
        resources.append((name, RES_IMAGE, bytes(fi_data), 0))

    # 3. Pages — RES_PAGE now holds a program's widget page (step 4).
    if "pages" in project:
        print('Error: "pages" is no longer supported (RES_PAGE now holds the '
              'widget page of a program: "widget_page": true)', file=sys.stderr)
        sys.exit(1)
    next_id = 1  # root = 0

    # 4. Programs — .fl → VM image (header + opcodes, metadata embedded)
    render_mode = project.get("render_mode", "dirty")
    # Project-level default; a program's own "widget_page" overrides it.
    widget_page = project.get("widget_page", False)
    prog_widget_count = 0
    prog_widget_hinted = False
    symbols = {}  # program name -> debug symbols (for --disasm)
    for prog in project.get("programs", []):
        name = prog["name"]
        source = project_dir / prog["source"]
        image_data = compile_program(str(source), include_dirs=include_dirs,
                                     render_mode=render_mode,
                                     widget_page=prog.get("widget_page", widget_page))
        exec_mode = prog.get("exec_mode", "ram")
        prog_flags = RES_FLAG_FLASH_EXEC if exec_mode == "flash" else 0
        resources.append((name, RES_PROGRAM, image_data, prog_flags))
        symbols[name] = getattr(image_data, "debug_symbols", {})
        page = getattr(image_data, "page", b"")
        if page:
            resources.append((name, RES_PAGE, page, 0))
        # Read widget_count back from v4 header (byte 7)
        if len(image_data) >= 9 and image_data[0] >= 4:
            prog_widget_count = max(prog_widget_count, image_data[7])
            # A hint was used if widget_count > static auto-count (next_widget_id)
            if image_data[7] > next_id:
                prog_widget_hinted = True

    # 5. Files — raw user data accessible from ferrite programs via fileOpen/Read.
    #    Max 15-char names; no processing — bytes stored verbatim.
    for f in project.get("files", []):
        name = f["name"]
        if len(name.encode("ascii")) > 15:
            print(f"Error: file name '{name}' exceeds 15 chars", file=sys.stderr)
            sys.exit(1)
        source = project_dir / f["source"]
        data = source.read_bytes()
        resources.append((name, RES_FILE, data, 0))

    # 6. System configuration — optional "memory" block sizes the runtime pools.
    memory = project.get("memory")
    if memory is not None:
        if not isinstance(memory, dict):
            raise ValueError('"memory" must be an object')
        resources.append((SYSCFG_NAME, RES_SYSCFG, build_syscfg(memory), 0))

    # 7. Build flash binary
    fs_binary = build_fs(project, resources, fs_base)
    if output_path is not None:
        Path(output_path).write_bytes(fs_binary)
    if fs_base != FS_BASE:
        print(f"  FS base: 0x{fs_base:X} (device '{device_id}') — "
              f"write image to this flash address")

    # Stats
    header_and_table = HEADER_SIZE + len(resources) * ENTRY_SIZE
    data_size = len(fs_binary) - header_and_table
    effective_widget_count = max(next_id, prog_widget_count)
    return {
        "resources": len(resources),
        "data_size": data_size,
        "total_size": len(fs_binary),
        "next_widget_id": next_id,
        "widget_count": effective_widget_count,
        "widget_count_hinted": prog_widget_hinted,
        "details": [(name, kind, len(data)) for name, kind, data, _flags in resources],
        "binary": fs_binary,
        "symbols": symbols,
    }


# --- Image dump (--disasm) ---

def dump_fs(binary: bytes, symbols: dict | None = None) -> str:
    """Describe every resource of a flash FS image; programs are
    disassembled with their widget page blocks inline. `symbols` maps a
    program name to its debug symbols (names for functions and variables)."""
    from ferrite_lang import format_image, disassemble_page_block

    if binary[:4] != MAGIC:
        raise ValueError("not a ferrite FS image (missing FERR magic)")
    version, scr_w, scr_h, count, checksum = struct.unpack_from("<HHHHI", binary, 4)
    table = binary[TABLE_OFFSET:TABLE_OFFSET + count * ENTRY_SIZE]
    entries = []
    for i in range(count):
        e = table[i * ENTRY_SIZE:(i + 1) * ENTRY_SIZE]
        name = e[:16].split(b"\0", 1)[0].decode("ascii", "replace")
        offset, size = struct.unpack_from("<II", e, 20)
        entries.append((name, e[16], offset, size, e[28]))
    # TOC offsets are absolute flash addresses; data follows the table.
    fs_base = entries[0][2] - (TABLE_OFFSET + count * ENTRY_SIZE) if entries else FS_BASE
    data = {(name, kind): binary[off - fs_base:off - fs_base + size]
            for name, kind, off, size, _ in entries}
    sum_ok = (sum(table) & 0xFFFFFFFF) == checksum

    out = [f"; ferrite FS v{version}, screen {scr_w}x{scr_h}, {count} resources, "
           f"base 0x{fs_base:X}, {len(binary)} bytes, checksum {'ok' if sum_ok else 'BAD'}",
           ";  #  kind     name              address    size  flags"]
    for i, (name, kind, off, size, flags) in enumerate(entries):
        flag_text = "flash-exec" if flags & RES_FLAG_FLASH_EXEC else ""
        out.append(f"; {i:2d}  {KIND_NAMES.get(kind, kind):<7}  {name:<16}  0x{off:06X}  {size:6d}  {flag_text}")

    for name, kind, off, size, flags in entries:
        blob = data[(name, kind)]
        title = f"{KIND_NAMES.get(kind, kind)} {name} ({size} B)"
        out += ["", f"; ==== {title} ===="]
        if kind == RES_PROGRAM:
            page = data.get((name, RES_PAGE), b"")
            out.append(format_image(blob, page, (symbols or {}).get(name)))
        elif kind == RES_PAGE:
            blocks, pos = [], 4
            while pos + 2 <= len(blob):
                blocks.append(pos)
                pos += 2 + struct.unpack_from("<H", blob, pos)[0]
            out.append(f"; widget page of program '{name}': {len(blocks)} blocks, "
                       f"shown under its W_LOAD instructions")
            if (name, RES_PROGRAM) not in data:
                for b in blocks:
                    out.append(f"; page+0x{b:04X}")
                    out += ["        " + l for l in disassemble_page_block(blob, b)]
        elif kind == RES_IMAGE and len(blob) >= 9:
            _magic, w, h, fl, colors = struct.unpack_from("<HHHBB", blob)
            mode = ("raw", "rle", "indexed+rle")[fl & 3] if fl & 3 < 3 else f"mode {fl & 3}"
            alpha = ", alpha" if fl & 0x04 else ""
            pal = f", {colors or 256} colors" if fl & 3 == 2 else ""
            out.append(f"; image_id {blob[8]}, {w}x{h}, {mode}{pal}{alpha}")
        elif kind == RES_FONT and len(blob) >= 4:
            glyphs, y_adv, font_id = struct.unpack_from("<HBB", blob)
            out.append(f"; font_id {font_id}, {glyphs} glyphs, line height {y_adv}")
        elif kind == RES_SYSCFG:
            fields = [f"{key}={struct.unpack_from(fmt, blob, off)[0]}"
                      for key, (off, fmt, _max) in SYSCFG_FIELDS.items()
                      if off + struct.calcsize(fmt) <= len(blob)]
            out.append("; " + ", ".join(fields) + "  (0 = firmware default)")
        else:
            head = " ".join(f"{b:02X}" for b in blob[:32])
            out.append(f"; {head}{' ...' if len(blob) > 32 else ''}")
    return "\n".join(out)


def show_info(project_path: str):
    """Proje dosyasının özetini göster (build yapmadan)."""
    project = json.loads(Path(project_path).read_text(encoding="utf-8"))
    screen = project.get("screen", [800, 480])
    fonts = project.get("fonts", [])
    images = project.get("images", [])
    programs = project.get("programs", [])
    files = project.get("files", [])

    total_res = len(fonts) + len(images) + len(programs) + len(files)

    print(f"Project: {project_path}")
    print(f"Screen:  {screen[0]}×{screen[1]}")
    print(f"Fonts:   {len(fonts)}")
    print(f"Images:  {len(images)}")
    print(f"Programs:{len(programs)}")
    print(f"Files:   {len(files)}")
    print(f"Total:   {total_res} resources")

    if total_res > MAX_RESOURCES:
        print(f"WARNING: {total_res} > {MAX_RESOURCES} max resources!")


# --- CLI ---

def main():
    args = sys.argv[1:]

    if not args or args[0] in ("-h", "--help"):
        print(__doc__)
        return

    project_path = args[0]

    if "--info" in args:
        show_info(project_path)
        return

    if "--expand" in args or "-E" in args:
        dump_expanded(project_path)
        return

    disasm = "--disasm" in args
    if disasm and not project_path.endswith(".json"):
        # An already built FS image: no source, so no symbol names.
        try:
            print(dump_fs(Path(project_path).read_bytes()))
        except (OSError, ValueError) as e:
            print(f"error: {e}", file=sys.stderr)
            sys.exit(1)
        return

    # Default output (--disasm alone builds in memory only)
    output_path = None if disasm else "flash.bin"
    for i, a in enumerate(args):
        if a == "-o" and i + 1 < len(args):
            output_path = args[i + 1]

    try:
        stats = build(project_path, output_path)
    except FileNotFoundError as e:
        print(f"error: file not found: {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        # CompileError or other build errors — show clean message
        print(f"error: {e}", file=sys.stderr)
        sys.exit(1)

    if disasm:
        print(dump_fs(stats["binary"], stats["symbols"]))
        return

    print(f"Built: {output_path}")
    print(f"  Resources: {stats['resources']}")
    print(f"  Data size: {stats['data_size']} bytes")
    print(f"  Total:     {stats['total_size']} bytes ({stats['total_size'] / 1024:.1f} KB)")
    wc_label = (f"{stats['widget_count']} (hinted)"
                if stats.get('widget_count_hinted') else
                f"{stats['widget_count']} (auto)")
    print(f"  Widgets:   {wc_label}")
    print()

    for name, kind, size in stats["details"]:
        print(f"  {KIND_NAMES.get(kind, '?'):>7s}  {name:<16s}  {size:>6d} bytes")


if __name__ == "__main__":
    main()
